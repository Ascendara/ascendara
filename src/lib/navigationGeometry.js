export const NAVIGATION_EDGE_PADDING_PX = 24;
export const NAVIGATION_COMPACT_ITEM_HEIGHT_PX = 8;
export const NAVIGATION_COMPACT_SEPARATOR_HEIGHT_PX = 12;
export const NAVIGATION_COMPACT_PADDING_Y_PX = 10;
export const NAVIGATION_SHELL_BORDER_PX = 1;
export const NAVIGATION_COMPACT_SAFE_GAP_PX = 6;

export const NAVIGATION_COMPACT_SAFE_AREA_PX =
  NAVIGATION_EDGE_PADDING_PX +
  Math.max(NAVIGATION_COMPACT_ITEM_HEIGHT_PX, NAVIGATION_COMPACT_SEPARATOR_HEIGHT_PX) +
  NAVIGATION_COMPACT_PADDING_Y_PX * 2 +
  NAVIGATION_SHELL_BORDER_PX * 2 +
  NAVIGATION_COMPACT_SAFE_GAP_PX;

export function getNavigationBottomSafeArea(pathname, compactDockOnScroll) {
  return pathname === "/settings" && compactDockOnScroll !== false
    ? NAVIGATION_COMPACT_SAFE_AREA_PX
    : 0;
}
