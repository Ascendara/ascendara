test("setup arguments: silent install, or the setup window when RAM limit is on", () => {
  const installDir = path.join("C:\\Games", "Some Game", "Some Game");
  const logPath = "C:\\Games\\Some Game\\fitgirl-install.log";
  assert.deepEqual(
    fitgirl.buildSetupArgs({ silent: true, limitRam: false, installDir, logPath }),
    [
      "/SP-",
      "/SILENT",
      "/SUPPRESSMSGBOXES",
      "/NORESTART",
      `/DIR="${installDir}"`,
      `/LOG="${logPath}"`,
    ]
  );
  const windowed = fitgirl.buildSetupArgs({
    silent: true,
    limitRam: true,
    installDir,
    logPath,
  });
  assert.ok(!windowed.includes("/SILENT") && !windowed.includes("/SUPPRESSMSGBOXES"));
  assert.ok(windowed.includes(`/DIR="${installDir}"`));
  const manual = fitgirl.buildSetupArgs({
    silent: false,
    limitRam: false,
    installDir,
    logPath,
  });
  assert.ok(!manual.includes("/SILENT"));
  assert.throws(
    () => fitgirl.buildSetupArgs({ silent: true, installDir: 'C:\\a"b', logPath }),
    /quote/
  );
  assert.throws(
    () => fitgirl.buildSetupArgs({ silent: true, installDir: "relative", logPath }),
    /absolute/
  );
});

test("only setup.exe in the download's own folder may run", () => {
  const gameDir = path.resolve("/games/Some Game");
  const ok = path.join(pack, "setup.exe");
  assert.equal(fitgirl.checkInstaller(ok, gameDir), pack);
  assert.equal(fitgirl.checkInstaller(path.join(pack, "SETUP.EXE"), gameDir), pack);
  assert.throws(
    () => fitgirl.checkInstaller(path.join(pack, "evil.exe"), gameDir),
    /setup\.exe/
  );
  assert.throws(
    () => fitgirl.checkInstaller(path.resolve("/elsewhere/setup.exe"), gameDir),
    /outside/
  );
  assert.throws(
    () => fitgirl.checkInstaller(path.join(gameDir, "..", "setup.exe"), gameDir),
    /outside/
  );
});

