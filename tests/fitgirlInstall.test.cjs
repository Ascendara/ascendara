test("cleanup lists only this pack's files and never the installed game", () => {
  const installDir = path.join(path.dirname(pack), "Some Game");
  const entries = [entry("fg-01.bin", "a"), entry("fg-optional-bonus.bin", "b", true)];
  const fsApi = {
    existsSync: p => !p.endsWith("fg-optional-bonus.bin"),
    readdirSync: dir => {
      assert.equal(dir, path.join(pack, "MD5"));
      return [
        { name: "fitgirl-bins.md5", isFile: () => true },
        { name: "QuickSFV.EXE", isFile: () => true },
        { name: "nested", isFile: () => false },
      ];
    },
  };
  const files = fitgirl.selectCleanup({
    packDir: pack,
    entries,
    installerPath: path.join(pack, "setup.exe"),
    installDir,
    fsApi,
  });
  assert.deepEqual(
    files.map(f => path.relative(pack, f)).sort(),
    ["MD5/QuickSFV.EXE", "MD5/fitgirl-bins.md5", "fg-01.bin", "setup.exe"]
      .map(p => p.split("/").join(path.sep))
      .sort()
  );
  // A pack folder that is also the install folder keeps everything.
  assert.deepEqual(
    fitgirl.selectCleanup({
      packDir: pack,
      entries,
      installerPath: path.join(pack, "setup.exe"),
      installDir: pack,
      fsApi,
    }),
    []
  );
});

test("an installed list resolves ..\\ paths from its own folder and stays inside", () => {
  const path = require("node:path");
  const {
    parseMd5List,
    installedMd5ListPath,
  } = require("../electron/modules/downloads/fitgirlInstall");
  const app = path.resolve("/games/Game");
  const listDir = path.dirname(installedMd5ListPath(app));
  assert.equal(path.basename(listDir), "_Redist");
  const hash = "0".repeat(32);
  const entries = parseMd5List(
    `${hash} *..\\bin\\game.exe\n${hash} *data\\a.pak\n`,
    app,
    listDir
  );
  assert.deepEqual(
    entries.map(item => item.filePath),
    [path.join(app, "bin", "game.exe"), path.join(app, "data", "a.pak")]
  );
  assert.throws(() => parseMd5List(`${hash} *..\\..\\x.exe\n`, app, listDir), /outside/);
});
