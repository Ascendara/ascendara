const { test } = require("node:test");
const assert = require("node:assert/strict");
const path = require("node:path");
const { EventEmitter } = require("node:events");
const crypto = require("node:crypto");
const fitgirl = require("../electron/modules/downloads/fitgirlInstall");

const pack = path.resolve("/games/Some Game/Some Game [FitGirl Repack]");
const md5 = text => crypto.createHash("md5").update(text).digest("hex");

test("a pack is FitGirl only when MD5/fitgirl-bins.md5 sits next to setup", () => {
  const seen = [];
  const fsApi = { existsSync: p => (seen.push(p), p.endsWith("fitgirl-bins.md5")) };
  assert.equal(fitgirl.isFitgirlPack(pack, fsApi), true);
  assert.equal(seen[0], path.join(pack, "MD5", "fitgirl-bins.md5"));
  assert.equal(fitgirl.isFitgirlPack(pack, { existsSync: () => false }), false);
  assert.equal(fitgirl.isFitgirlPack("", fsApi), false);
});

test("md5 lists parse CRLF, comments, star and plain separators, subfolders", () => {
  const text = [
    "; Generated by QuickSFV",
    "",
    "0123456789abcdef0123456789ABCDEF *fg-01.bin",
    "fedcba9876543210fedcba9876543210  fg-optional-bonus.bin",
    "00000000000000000000000000000000 *..\\fg-02.bin",
    "11111111111111111111111111111111 *sub\\fg-selective-french.bin",
  ].join("\r\n");
  const entries = fitgirl.parseMd5List(text, pack);
  assert.deepEqual(
    entries.map(e => [e.hash, path.relative(pack, e.filePath), e.optional]),
    [
      ["0123456789abcdef0123456789abcdef", "fg-01.bin", false],
      ["fedcba9876543210fedcba9876543210", "fg-optional-bonus.bin", true],
      ["00000000000000000000000000000000", "fg-02.bin", false],
      [
        "11111111111111111111111111111111",
        path.join("sub", "fg-selective-french.bin"),
        true,
      ],
    ]
  );
});

test("md5 lists reject paths that escape the pack folder", () => {
  for (const bad of [
    "..\\..\\evil.bin",
    "/etc/passwd",
    "C:\\Windows\\evil.bin",
    "sub\\..\\..\\..\\evil.bin",
  ]) {
    assert.throws(
      () => fitgirl.parseMd5List(`0123456789abcdef0123456789abcdef *${bad}`, pack),
      /outside the pack/,
      bad
    );
  }
  assert.throws(() => fitgirl.parseMd5List("not a hash line", pack), /line 1/);
  assert.throws(() => fitgirl.parseMd5List("; only a comment", pack), /no files/);
});

function fakeFs(files) {
  return {
    existsSync: p => files.has(p),
    statSync: p => {
      if (!files.has(p)) throw Object.assign(new Error("ENOENT"), { code: "ENOENT" });
      return { size: files.get(p).length, isFile: () => true };
    },
    createReadStream: p => {
      const stream = new EventEmitter();
      stream.destroy = () => (stream.destroyed = true);
      const data = Buffer.from(files.get(p));
      setImmediate(() => {
        for (let i = 0; i < data.length && !stream.destroyed; i += 2) {
          stream.emit("data", data.subarray(i, i + 2));
        }
        if (!stream.destroyed) stream.emit("end");
      });
      return stream;
    },
  };
}

const entry = (name, content, optional = false) => ({
  hash: md5(content),
  filePath: path.join(pack, name),
  name,
  optional,
});

test("verify streams every listed file and reports bad, missing and skipped", async () => {
  const files = new Map([
    [path.join(pack, "fg-01.bin"), "good-one"],
    [path.join(pack, "fg-02.bin"), "tampered"],
  ]);
  const entries = [
    entry("fg-01.bin", "good-one"),
    entry("fg-02.bin", "original"),
    entry("fg-03.bin", "never downloaded"),
    entry("fg-optional-bonus.bin", "skipped part", true),
  ];
  const progress = [];
  let clock = 0;
  const result = await fitgirl.verifyPack(entries, {
    fsApi: fakeFs(files),
    onProgress: p => progress.push(p),
    now: () => (clock += 1000),
  });
  assert.equal(result.ok, false);
  assert.deepEqual(result.passed, ["fg-01.bin"]);
  assert.deepEqual(result.bad, ["fg-02.bin"]);
  assert.deepEqual(result.missing, ["fg-03.bin"]);
  assert.deepEqual(result.skipped, ["fg-optional-bonus.bin"]);
  assert.equal(progress.at(-1).bytesDone, 16);
  assert.equal(progress.at(-1).bytesTotal, 16);
  assert.ok(progress.every(p => p.bytesDone <= p.bytesTotal));
});

test("verify passes when only optional parts are absent, and throttles progress", async () => {
  const files = new Map([[path.join(pack, "fg-01.bin"), "x".repeat(40)]]);
  const progress = [];
  const result = await fitgirl.verifyPack(
    [entry("fg-01.bin", "x".repeat(40)), entry("fg-selective-german.bin", "y", true)],
    { fsApi: fakeFs(files), onProgress: p => progress.push(p), now: () => 0 }
  );
  assert.equal(result.ok, true);
  assert.deepEqual(result.skipped, ["fg-selective-german.bin"]);
  // Same timestamp for every chunk: only the first update and the final one get through.
  assert.equal(progress.length, 2);
});

